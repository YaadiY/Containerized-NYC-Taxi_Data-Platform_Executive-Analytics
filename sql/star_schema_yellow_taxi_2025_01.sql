-- Build a trip-level star schema for the January 2025 Silver dataset.
-- Grain: one fact row per row in yellow_taxi_trips_2025_01_clean.
-- This script replaces only the derived tables in the analytics schema.

BEGIN;

CREATE SCHEMA IF NOT EXISTS analytics;

DROP TABLE IF EXISTS analytics.fact_yellow_taxi_trip_2025_01;
DROP TABLE IF EXISTS analytics.dim_payment_type;
DROP TABLE IF EXISTS analytics.dim_location;
DROP TABLE IF EXISTS analytics.dim_date;

-- Calendar dimension used in two roles: pickup date and dropoff date.
CREATE TABLE analytics.dim_date (
    date_key integer PRIMARY KEY,
    calendar_date date NOT NULL UNIQUE,
    year_number smallint NOT NULL,
    quarter_number smallint NOT NULL,
    month_number smallint NOT NULL,
    day_of_month smallint NOT NULL,
    weekday_number smallint NOT NULL,
    weekday_name text NOT NULL,
    is_weekend boolean NOT NULL
);

INSERT INTO analytics.dim_date (
    date_key, calendar_date, year_number, quarter_number, month_number,
    day_of_month, weekday_number, weekday_name, is_weekend
)
SELECT
    TO_CHAR(calendar_date, 'YYYYMMDD')::integer,
    calendar_date::date,
    EXTRACT(YEAR FROM calendar_date)::smallint,
    EXTRACT(QUARTER FROM calendar_date)::smallint,
    EXTRACT(MONTH FROM calendar_date)::smallint,
    EXTRACT(DAY FROM calendar_date)::smallint,
    EXTRACT(ISODOW FROM calendar_date)::smallint,
    TO_CHAR(calendar_date, 'FMDay'),
    EXTRACT(ISODOW FROM calendar_date) IN (6, 7)
FROM generate_series(
    (SELECT LEAST(MIN(pickup_date), MIN(tpep_dropoff_datetime::date))
     FROM yellow_taxi_trips_2025_01_clean),
    (SELECT GREATEST(MAX(pickup_date), MAX(tpep_dropoff_datetime::date))
     FROM yellow_taxi_trips_2025_01_clean),
    INTERVAL '1 day'
) AS dates(calendar_date);

-- One location row per taxi-zone LocationID. The dimension is role-played
-- by the fact table as both pickup_location_key and dropoff_location_key.
CREATE TABLE analytics.dim_location (
    location_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id integer UNIQUE,
    borough text NOT NULL,
    zone_name text NOT NULL,
    service_zone text,
    is_unknown boolean NOT NULL DEFAULT false
);

-- Key 0 represents NULL or unmapped source location IDs.
INSERT INTO analytics.dim_location
    (location_key, location_id, borough, zone_name, service_zone, is_unknown)
VALUES
    (0, NULL, 'Unknown / unmapped', 'Unknown / unmapped', NULL, true);

INSERT INTO analytics.dim_location
    (location_id, borough, zone_name, service_zone, is_unknown)
SELECT
    "LocationID",
    COALESCE("Borough", 'Unknown'),
    COALESCE("Zone", 'Unknown / unmapped'),
    "service_zone",
    false
FROM zones;

-- Payment codes are retained as source values and given readable labels.
CREATE TABLE analytics.dim_payment_type (
    payment_type_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_type_code bigint UNIQUE,
    payment_type_label text NOT NULL,
    is_unknown boolean NOT NULL DEFAULT false
);

-- Key 0 handles NULL payment codes; other unmapped numeric codes are retained.
INSERT INTO analytics.dim_payment_type
    (payment_type_key, payment_type_code, payment_type_label, is_unknown)
VALUES
    (0, NULL, 'Missing payment type', true);

INSERT INTO analytics.dim_payment_type
    (payment_type_code, payment_type_label, is_unknown)
SELECT DISTINCT
    payment_type,
    CASE payment_type
        WHEN 0 THEN 'Flex Fare'
        WHEN 1 THEN 'Credit card'
        WHEN 2 THEN 'Cash'
        WHEN 3 THEN 'No charge'
        WHEN 4 THEN 'Dispute'
        WHEN 5 THEN 'Unknown'
        WHEN 6 THEN 'Voided trip'
        ELSE 'Unmapped code: ' || payment_type::text
    END,
    payment_type NOT BETWEEN 0 AND 6
FROM yellow_taxi_trips_2025_01_clean
WHERE payment_type IS NOT NULL;

-- The fact contains measurable trip events and foreign keys to dimensions.
-- It has a warehouse-generated key because source trips have no declared PK.
CREATE TABLE analytics.fact_yellow_taxi_trip_2025_01 (
    trip_fact_key bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    pickup_date_key integer NOT NULL REFERENCES analytics.dim_date(date_key),
    dropoff_date_key integer NOT NULL REFERENCES analytics.dim_date(date_key),
    pickup_location_key integer NOT NULL REFERENCES analytics.dim_location(location_key),
    dropoff_location_key integer NOT NULL REFERENCES analytics.dim_location(location_key),
    payment_type_key integer NOT NULL REFERENCES analytics.dim_payment_type(payment_type_key),
    vendor_id bigint,
    pickup_datetime timestamp NOT NULL,
    dropoff_datetime timestamp NOT NULL,
    passenger_count bigint,
    trip_distance double precision,
    trip_duration_minutes numeric(12, 2),
    ratecode_id bigint,
    store_and_fwd_flag text,
    fare_amount double precision,
    extra double precision,
    mta_tax double precision,
    tip_amount double precision,
    tolls_amount double precision,
    improvement_surcharge double precision,
    congestion_surcharge double precision,
    airport_fee double precision,
    cbd_congestion_fee double precision,
    total_amount double precision,
    trip_count smallint NOT NULL DEFAULT 1,
    has_review_flag boolean NOT NULL,
    negative_fare_flag boolean NOT NULL,
    negative_total_flag boolean NOT NULL
);

INSERT INTO analytics.fact_yellow_taxi_trip_2025_01 (
    pickup_date_key, dropoff_date_key,
    pickup_location_key, dropoff_location_key, payment_type_key,
    vendor_id, pickup_datetime, dropoff_datetime, passenger_count,
    trip_distance, trip_duration_minutes, ratecode_id, store_and_fwd_flag,
    fare_amount, extra, mta_tax, tip_amount, tolls_amount,
    improvement_surcharge, congestion_surcharge, airport_fee,
    cbd_congestion_fee, total_amount,
    trip_count, has_review_flag, negative_fare_flag, negative_total_flag
)
SELECT
    pickup_date_dim.date_key,
    dropoff_date_dim.date_key,
    COALESCE(pickup_location.location_key, 0),
    COALESCE(dropoff_location.location_key, 0),
    COALESCE(payment.payment_type_key, 0),
    trips."VendorID",
    trips.tpep_pickup_datetime,
    trips.tpep_dropoff_datetime,
    trips.passenger_count,
    trips.trip_distance,
    trips.trip_duration_minutes,
    trips."RatecodeID",
    trips.store_and_fwd_flag,
    trips.fare_amount,
    trips.extra,
    trips.mta_tax,
    trips.tip_amount,
    trips.tolls_amount,
    trips.improvement_surcharge,
    trips.congestion_surcharge,
    trips."Airport_fee",
    trips.cbd_congestion_fee,
    trips.total_amount,
    1,
    CASE WHEN (
        trips.trip_duration_minutes = 0
        OR trips.trip_distance = 0
        OR trips.passenger_count IS NULL
        OR trips.fare_amount < 0
        OR trips.total_amount < 0
        OR trips.trip_distance > 200
        OR trips.trip_duration_minutes > 1440
        OR trips.total_amount > 1000
    ) THEN true ELSE false END,
    COALESCE(trips.fare_amount < 0, false),
    COALESCE(trips.total_amount < 0, false)
FROM yellow_taxi_trips_2025_01_clean AS trips
JOIN analytics.dim_date AS pickup_date_dim
    ON pickup_date_dim.calendar_date = trips.pickup_date
JOIN analytics.dim_date AS dropoff_date_dim
    ON dropoff_date_dim.calendar_date = trips.tpep_dropoff_datetime::date
LEFT JOIN analytics.dim_location AS pickup_location
    ON pickup_location.location_id = trips."PULocationID"
LEFT JOIN analytics.dim_location AS dropoff_location
    ON dropoff_location.location_id = trips."DOLocationID"
LEFT JOIN analytics.dim_payment_type AS payment
    ON payment.payment_type_code = trips.payment_type;

CREATE INDEX idx_fact_yellow_taxi_2025_01_pickup_date
    ON analytics.fact_yellow_taxi_trip_2025_01 (pickup_date_key);
CREATE INDEX idx_fact_yellow_taxi_2025_01_pickup_location
    ON analytics.fact_yellow_taxi_trip_2025_01 (pickup_location_key);
CREATE INDEX idx_fact_yellow_taxi_2025_01_dropoff_location
    ON analytics.fact_yellow_taxi_trip_2025_01 (dropoff_location_key);
CREATE INDEX idx_fact_yellow_taxi_2025_01_payment
    ON analytics.fact_yellow_taxi_trip_2025_01 (payment_type_key);

ANALYZE analytics.fact_yellow_taxi_trip_2025_01;

COMMIT;

-- Reconciliation check: fact rows should equal Silver rows, and trip_count
-- should equal one per fact row. Run separately after the model is built.
SELECT
    (SELECT COUNT(*) FROM yellow_taxi_trips_2025_01_clean) AS silver_rows,
    (SELECT COUNT(*) FROM analytics.fact_yellow_taxi_trip_2025_01) AS fact_rows,
    (SELECT SUM(trip_count) FROM analytics.fact_yellow_taxi_trip_2025_01) AS fact_trip_count,
    (SELECT COUNT(*) FROM yellow_taxi_trips_2025_01_clean)
        = (SELECT COUNT(*) FROM analytics.fact_yellow_taxi_trip_2025_01)
        AS rows_reconcile;

-- Example star-schema query: daily trips by pickup borough and zone.
SELECT
    date_dim.calendar_date AS pickup_date,
    location.borough AS pickup_borough,
    location.zone_name AS pickup_zone,
    SUM(fact.trip_count) AS total_trips
FROM analytics.fact_yellow_taxi_trip_2025_01 AS fact
JOIN analytics.dim_date AS date_dim
    ON date_dim.date_key = fact.pickup_date_key
JOIN analytics.dim_location AS location
    ON location.location_key = fact.pickup_location_key
GROUP BY date_dim.calendar_date, location.borough, location.zone_name
ORDER BY pickup_date, total_trips DESC;
